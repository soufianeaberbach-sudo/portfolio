export type PortfolioTerms = (typeof terms)['en'];

/** The page language, read in the browser from <html lang>. */
export const clientLocale = (): Locale => {
  const lang = typeof document === 'undefined' ? 'en' : document.documentElement.lang;
  return isLocale(lang) ? lang : 'en';
};

/** Looks a term up by its English source, falling back to the source. */
export const term = <K extends 'shots' | 'scenes' | 'views' | 'menTitles'>(locale: Locale, group: K, english: string): string =>
  (terms[locale][group] as Record<string, string>)[english] ?? english;

export const categoryName = (locale: Locale, id: string): string =>
  (terms[locale].categories as Record<string, string>)[id] ?? (terms.en.categories as Record<string, string>)[id] ?? id;
